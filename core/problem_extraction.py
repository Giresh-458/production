def validate_claim_against_evidence(claim: str, evidence: List[str]) -> ClaimValidation:
    """
    Validates an arbitrary claim against a list of evidence spans.
    Fails if the claim contains facts (numbers/entities) not supported by the evidence.
    """
    import re
    words = re.findall(r'\b\w+\b', claim)
    evidence_lower = " ".join(evidence).lower()
    
    whitelist = {"problem", "challenge", "limitation", "bottleneck", "issue", "system", "current", "scalability", "performance", "requires", "cause", "causes", "create", "creates", "however", "therefore", "significant", "operational", "infrastructure", "verification", "transaction", "transactions", "latency", "high", "volume", "volumes", "scale", "bottlenecks", "limitations", "rises", "over", "above", "below", "associated", "increased", "increase", "decrease", "decreased"}
    
    for w in words:
        if not w: continue
        if w.isdigit():
            if w not in evidence_lower and w not in " ".join(evidence):
                return ClaimValidation(is_supported=False, score=0.0, reason=f"Unsupported number: {w}")
        if len(w) > 4:
            w_lower = w.lower()
            if w_lower not in whitelist and w_lower not in evidence_lower:
                if w_lower[:-1] not in evidence_lower and w_lower[:-2] not in evidence_lower:
                    return ClaimValidation(is_supported=False, score=0.0, reason=f"Unsupported entity: {w}")
    return ClaimValidation(is_supported=True, score=1.0, reason="All claim entities supported by evidence")

def _validate_refinement(refined_text: str, evidence_text: str) -> bool:
    """
    Determines whether an LLM refinement stays within the factual boundary of the original evidence.
    Args:
        refined_text: The compressed or refined statement generated by the LLM.
        evidence_text: The original source evidence text.
    """
    return validate_claim_against_evidence(refined_text, [evidence_text]).is_supported

def _refine_with_llm(candidate_problem: str, evidence: list[str]) -> str | None:
    if not generate:
        return None

    evidence_text = "\\n".join(evidence)
    prompt = f"""Refine the following candidate problem into a clear, concise, single-sentence research problem statement.
DO NOT introduce any new organizations, domains, populations, metrics, or technical capabilities that are not present in the evidence.

Evidence:
{evidence_text}

Candidate Problem:
{candidate_problem}

Output only the refined single-sentence problem statement, nothing else."""
    try:
        refined = generate(prompt)
        refined = refined.strip().strip('"').strip()
        if not refined or len(refined) < 10:
            return None
        
        if _validate_refinement(refined, evidence_text):
            return refined
    except Exception:
        pass
    return None

def _is_objective_or_task_statement(text: str) -> bool:
    """Reject programme objectives and implementation instructions as problem evidence.

    This is deliberately conservative and only applies to funding extraction. A call's
    objective may mention risks or gaps without establishing that the sentence itself
    describes an existing problem. Such text remains available in the source record but
    is not promoted to a problem signal.
    """
    value = re.sub(r"\s+", " ", str(text or "")).strip().lower()
    patterns = (
        r"^(?:the\s+)?(?:call|programme|program|initiative|funding opportunity)\s+"
        r"(?:is designed to|aims? to|seeks? to|is intended to|has the objective of|focus(?:es)? on|focus\s+is\s+on)\b",
        r"^(?:the\s+)?(?:action|project|proposal|work programme|funded action)\s+"
        r"should\s+(?:address|track|develop|deliver|implement|provide|support|assess|evaluate|"
        r"analyse|analyze|identify|establish|investigate|improve|reduce)\b",
        r"^(?:the\s+)?(?:action|project|proposal)\s+is expected to\b",
        # Requirements placed on the funded consortium/network/pilot describe
        # what applicants must do, not an existing problem (observed live:
        # "The network should integrate coordinators of living labs projects...").
        r"^(?:the\s+)?(?:network|consortium|consortia|partnership|living labs?|pilots?|"
        r"selected projects?|successful (?:applicants?|proposals?)|beneficiar(?:y|ies))\s+"
        r"(?:should|must|shall|will|are expected to|is expected to|are required to|is required to)\s+\w+",
        r"^(?:expected outcomes?|objectives?|scope of work|tasks?|deliverables?)\s*:",
        r"^(?:potential\s+)?(?:application|use|target)\s+(?:fields?|areas?|domains?|sectors?)\s+include\b",
        r"^(?:potential\s+)?(?:application fields|application areas|use cases)\s+include\b",
        # Applicant guidance, topic lists, capability descriptions and desired
        # outcomes are not evidence that a technical problem currently exists.
        r"^(?:you can choose what you would like to cover|the focus should be on|focus should be on)\b",
        r"^(?:policy makers?|decision makers?|stakeholders?)\s+(?:are|become|will be)\s+more\s+(?:aware|informed|capable|able)\b",
        r"^(?:reduced vulnerability|increased resilience|improved resilience|lowering flood risks|increasing resilience)\b",
        r"^(?:it returns|the platform returns|the system returns|the tool returns|our product|the platform provides|the system provides)\b",
        r"^(?:grant size|approved so far|applications paused|skills needed|live grants|contact|you are welcome to|welcome to join)\b",
        r"^(?:deep tech for|developing and commercially scaling)\b",
        r"^(?:accelerating|accelerate|promoting|promote|supporting|support|enabling|enable)\s+"
        r"(?:the\s+)?(?:market uptake|commercial uptake|adoption|deployment|innovation|business growth)\b",
        r"^(?:build|create|develop|implement|track|submit|apply|provide|support|assess|evaluate|"
        r"identify|establish|investigate|coordinate|explore|strengthen|secure|maintain)\b",
        r"^(?:steps?\s+to\s+(?:ensure|secure|improve|maintain)|take\s+steps\s+to\s+"
        r"(?:ensure|secure|improve|maintain)|acting\s+on\s+this\s+offers\s+an\s+opportunity)\b",
    )
    return any(re.search(pattern, value, flags=re.IGNORECASE) for pattern in patterns)


def _is_administrative_or_financial_rule(text: str) -> bool:
    """Reject grant-administration rules that contain limitation vocabulary.

    Budget caps, subcontracting proportionality, and eligible-cost rules are
    conditions of the grant, not evidence of a research or technical problem.
    """
    value = re.sub(r"\s+", " ", str(text or "")).strip().lower()
    patterns = (
        # Strategic-autonomy language in Horizon eligibility sections explains
        # the geographic/control restriction; it is not a technical research
        # problem statement for the funded project.
        r"\bsafeguard the (?:union|european union)'?s strategic assets\b",
        r"\btechnological dependency on a non[- ]eu source\b",
        r"\bstrategic weaknesses, vulnerabilities and high[- ]risk dependencies\b",
        r"\bsubcontracting\b.{0,180}\b(?:proportionate|limited|limit|cap|must not exceed)\b",
        r"\b(?:eligible costs?|funding rate|grant amount|maximum funding|total budget|budget ceiling|"
        r"co[- ]funding|indirect costs?|overheads?)\b.{0,180}\b"
        r"(?:limited|limit|cap|maximum|up to|per project|proportionate|must not exceed|eligible)\b",
        r"\b(?:limited|limit|cap|maximum|must not exceed)\b.{0,140}\b"
        r"(?:subcontracting|eligible costs?|funding rate|grant amount|budget|cost categories)\b",
        r"^limited parts\b.{0,180}\bsubcontracting\b",
        r"^applicants? should not apply if\b",
        r"\bapplicants? should not apply if\b",
        r"\b(?:venture|startup|company)\b.{0,100}\bunable to sign\b.{0,40}\bSAFE\b",
        # Eligibility and geographic restrictions often contain words such as
        # "limited" or "risk", but they describe who may apply, not a research
        # or technical problem.
        r"\b(?:participation|eligibility|applicants?|beneficiaries|legal entities|institutions?)\b.{0,180}\b(?:limited|restricted|confined)\s+to\b",
        r"\b(?:applicants?|beneficiaries|legal entities|institutions?)\b.{0,180}\b(?:must be|established in|registered in|incorporated in|located in|based in)\b",
        r"\bto qualify\b.{0,180}\b(?:institution|applicant|beneficiary|legal entit|must be|established in|registered in)\b",
        # Scope lists and programme rules can use "limited" without describing
        # a limitation in the research or technology.
        r"\b(?:including but not limited to|not limited to)\b",
        r"\b(?:research(?:\s+or\s+analytical)?|analytical)\s+(?:effort|work)\b.{0,180}\b(?:research partners?|consultants?|subcontractors?|third parties)\b",
    )
    return any(re.search(pattern, value, flags=re.IGNORECASE) for pattern in patterns)


def _is_genuine_limitation(text: str) -> bool:
    """Recognize explicit problem/risk language without treating action verbs as problems."""
    t = text.strip().lower()
    strong = (
        r"\b(?:cannot|can't|fails?|failed|unable|lacks?|lacking|insufficient|limited|limitation|bottleneck|barrier|"
        r"unresolved|unknown|unclear|inadequate|impractical|fragile|unreliable|poor performance|"
        r"risk|risks|threat|threats|vulnerabilities|shortage|scarcity|fragmented|degraded|"
        r"not (?:yet )?(?:possible|well understood|addressed|supported|solved)|remains a challenge|friction)\b|"
        r"\blimits?\s+(?:the\s+)?(?:ability|access|availability|capacity|performance|adoption|reliability|resilience)\b"
    )
    if not re.search(strong, t):
        return False
    if len(t.split()) < 6:
        return False
    if re.match(r"^(greetings|welcome|copyright|all rights reserved|please contact|we are thrilled)\b", t):
        return False
    return True


# ---------------------------------------------------------------------------
# Funding (Batch-1) problem-sentence quality.
# Observed live on official EU topic text (2026-11-20 audit): about half of the
# selected "problems" were instructions ("Projects should consider ..."),
# encouragements ("Cooperation ... is encouraged"), expected outcomes ("Project
# results are expected to ..."), definitions ("maladaptation refers to ..."),
# list items ("b) To address ...") or mid-sentence fragments, mostly selected
# because they contained "risk" inside a technical compound ("risk assessment").
# ---------------------------------------------------------------------------
_FUNDING_RISK_COMPOUND = re.compile(
    r"\b(?:disaster\s+)?risks?[\s-]+(?:assessments?|management|mitigation|reduction|analys[ie]s|analytics|"
    r"governance|monitoring|modelling|modeling|evaluation|informed)\b",
    re.IGNORECASE,
)
_FUNDING_EXTRA_LIMITATION = re.compile(
    r"\b(?:gaps?|uncertaint(?:y|ies))\b[^.;]{0,80}\bremains?\b|"
    r"\bremains?\s+(?:poorly|largely|still)?\s*(?:understood|unknown|unclear|uncertain|limited|unaddressed)\b|"
    r"\bknowledge gaps?\b|\bbackfire\b|\bunintended (?:consequences|effects|outcomes)\b|"
    r"\bneed for (?:more|further|additional|new) (?:research|evidence|knowledge)\b|"
    r"\b(?:further|more|additional) research is (?:needed|required)\b",
    re.IGNORECASE,
)


def _is_funding_non_problem_sentence(text: str) -> bool:
    """True for funding-call text that is not a problem statement by its form."""
    value = re.sub(r"\s+", " ", str(text or "")).strip()
    low = value.casefold()
    if not value:
        return True
    # Fragments and list items: a source sentence starts with a capital, digit or quote.
    if re.match(r"^[a-z]", value):
        return True
    if re.match(r"^(?:[a-h]|[ivx]{1,4})\)\s", low) or re.match(r"^(?:etc\.?\)|\))", low):
        return True
    # Encouragement and applicant instructions.
    if re.search(r"\b(?:is|are)\s+(?:also\s+|strongly\s+|particularly\s+)?encouraged\b", low):
        return True
    if re.match(r"^(?:[\w'-]+\s+){0,3}(?:should|must|shall|are expected to|is expected to|will be expected to)\b", low):
        return True
    if re.match(r"^(?:solutions sought|project results are expected|expected outcomes?\b|proposals are expected)", low):
        return True
    if re.search(r"\b(?:is|are)\s+(?:also\s+)?expected to\b", low) or re.search(
        r"\b(?:proposals?|projects?|applicants?|consortia|consortium|actions?)\b[^.;]{0,60}\b(?:should|must|shall)\b", low
    ):
        return True
    # Definitions, meta-descriptions of the topic, and expected-outcome phrasing.
    if re.search(r"\b(?:refers? to|is defined as|are defined as)\b", low):
        return True
    if re.match(r"^(?:this|the)\s+(?:topic|call|action)\s+(?:is|will|covers|includes|addresses|aims)\b", low):
        return True
    if re.match(r"^the focus (?:is|should be|will be) on\b", low):
        return True
    if re.match(r"^(?:reduced|increased|improved|enhanced|strengthened|better|greater)\s", low):
        return True
    # Application conditions.
    if re.search(r"\bat the time of (?:application|submission)\b", low):
        return True
    # What proposals may do, opportunity/benefit framing, and listed policy targets.
    if re.search(r"\b(?:proposals?|applicants?|projects?)\s+(?:can|may|could)\b", low):
        return True
    if re.search(r"\b(?:can|could|will|may)\s+(?:provide|help|offer|enable|support)\b|"
                 r"\b(?:offers?|provides?|presents?)\s+(?:a\s+|an\s+)?(?:unique\s+|new\s+|key\s+)?opportunit", low):
        return True
    if re.search(r"\b(?:commitments?|targets?)\s*:", low):
        return True
    return False


_EU_EXPECTED_OUTCOME_SECTION = re.compile(
    r"(?is)\bexpected outcomes?\s*:.*?(?=\bscope\s*:)"
)


def _strip_expected_outcome_section(text: str) -> str:
    """Drop an EU topic's "Expected Outcome:" section (ends at "Scope:").

    Expected outcomes describe the intended results of funded projects, never an
    existing problem. Only removed when the publisher's "Scope:" heading follows,
    so unstructured pages are left untouched.
    """
    return _EU_EXPECTED_OUTCOME_SECTION.sub(" ", str(text or ""))


_RISK_ONLY_TERMS = re.compile(r"\b(?:risks?|threats?)\b", re.IGNORECASE)
_RISK_PROBLEM_CONTEXT = re.compile(
    r"\b(?:pose[sd]?|posing|faces?|facing|exposed|increas\w*|growing|heightened|serious|severe|"
    r"significant|major|at risk|threaten\w*|vulnerab\w*)\b",
    re.IGNORECASE,
)


def _is_funding_limitation(text: str) -> bool:
    """Limitation test for funding text with technical "risk" compounds neutralized.

    A sentence whose only problem word is "risk"/"threat" must also say the risk
    is posed, faced, increasing or serious; naming a risk topic ("... related to
    the health risks of climate change") is not a problem statement.
    """
    neutral = _FUNDING_RISK_COMPOUND.sub(" ", str(text or ""))
    if (
        _is_genuine_limitation(neutral)
        and not _is_genuine_limitation(_RISK_ONLY_TERMS.sub(" ", neutral))
        and not _RISK_PROBLEM_CONTEXT.search(neutral)
    ):
        neutral = ""
    return _is_genuine_limitation(neutral) or (
        len(str(text or "").split()) >= 6 and bool(_FUNDING_EXTRA_LIMITATION.search(str(text or "")))
    )


def _clean_funding_candidate_text(text: str) -> str:
    """Strip page chrome/Markdown from a candidate while preserving source wording."""
    from html import unescape

    value = unescape(str(text or ""))
    value = re.sub(r"!\[([^\]]*)\]\([^)]*\)", r"\1 ", value)
    value = re.sub(r"\[([^\]]{1,300})\]\((?:https?://|/)[^)]*\)", r"\1", value)
    value = re.sub(r"<https?://[^>]+>", " ", value)
    value = re.sub(r"https?://\S+", " ", value)
    value = re.sub(r"(?m)^\s{0,3}#{1,6}\s*", "", value)
    value = re.sub(r"[*_~]{1,3}", "", value)
    value = re.sub(r"^\s*(?:[-*•]|\d+[.)])\s*", "", value)
    value = re.sub(r"^\s*(?:\[\d{1,3}\]\s*)+", "", value)
    value = re.sub(r"\s+", " ", value).strip(" \t\r\n-•:")
    value = re.sub(
        r"^(?:expected outcomes?|scope|description|background|rationale|overview|problem preview)\s*:\s*",
        "", value, flags=re.IGNORECASE,
    ).strip()
    return value


def _funding_candidate_segments(paragraph: str) -> list[str]:
    """Split funding copy into source-grounded, concise candidates without hard truncation."""
    raw = str(paragraph or "").strip()
    if not raw:
        return []

    # Split Markdown list items before whitespace cleanup; otherwise independent
    # grant-purpose bullets can be concatenated into one misleading long signal.
    chunks = re.split(r"\n\s*(?=(?:[-*•]|\d+[.)])\s+)", raw)
    candidates = []
    for chunk in chunks:
        # Semicolon-separated clauses often encode distinct research needs or
        # populations in EU call text. Keep the source wording, but evaluate each
        # clause independently rather than cutting a sentence at an arbitrary index.
        cleaned = _clean_funding_candidate_text(chunk)
        if not cleaned:
            continue
        parts = re.split(r"(?<=[.!?])\s+(?=[A-Z0-9\"'(])|;\s+", cleaned)
        for part in parts:
            candidate = _clean_funding_candidate_text(part)
            if len(candidate.split()) < 6:
                continue
            # A semicolon list item such as "or lack of resources, funds, or
            # incentives ..." is a fragment of an enumeration, not a
            # self-contained problem statement (observed live on
            # HORIZON-NEB-2026-01-BUSINESS-03).
            if re.match(r"(?:or|and|nor|but)\b", candidate, flags=re.IGNORECASE):
                continue
            # Do not truncate a source statement arbitrarily. Some official calls
            # place a genuine risk/challenge and an eligibility restriction in one
            # long sentence; retain only complete comma-delimited clauses that
            # independently express a limitation, and continue to reject applicant
            # rules and administrative constraints below.
            if len(candidate) > 320:
                clauses = [
                    _clean_funding_candidate_text(clause)
                    for clause in re.split(r",\s+", candidate)
                ]
                for clause in clauses:
                    if (
                        6 <= len(clause.split())
                        and len(clause) <= 320
                        and _is_genuine_limitation(clause)
                        and not _is_administrative_or_financial_rule(clause)
                        and not _is_objective_or_task_statement(clause)
                    ):
                        candidates.append(clause)
                continue
            candidates.append(candidate)
    return candidates

def _is_structured_problem_signal(text: str, *, title: str = "", research_area: Optional[str] = None, agent_name: Optional[str] = None) -> tuple[bool, str]:
    """Return whether a source-framed sentence is itself a problem/challenge signal.

    Some high-value collection layers state the problem structurally rather than with
    limitation vocabulary (e.g. ``Challenge track: build ...`` or ``Incident report: ...``).
    This helper only promotes sentences whose *source framing* explicitly identifies the
    sentence as a challenge, incident, benchmark need, gap, or required capability. It
    therefore broadens recall without turning arbitrary descriptive prose into a problem.
    """
    t = text.strip()
    low = t.lower()
    agent = (agent_name or "").strip().lower()
    area = normalize_area(research_area) or ""

    framed_prefixes = (
        ("challenge track:", "challenge_statement"),
        ("challenge:", "challenge_statement"),
        ("problem statement:", "problem_statement"),
        ("problem:", "problem_statement"),
        ("incident report:", "incident"),
        ("root cause:", "root_cause"),
        ("dataset and benchmark description:", "benchmark_need"),
        ("benchmark description:", "benchmark_need"),
        ("research gap:", "research_gap"),
        ("known gap:", "research_gap"),
        ("ecosystem need:", "ecosystem_need"),
        ("technical challenge:", "technical_challenge"),
    )
    for prefix, kind in framed_prefixes:
        if low.startswith(prefix) and len(t.split()) >= 7:
            return True, kind

    # Collector-specific source framing is intentionally narrow. These patterns are
    # common in the corresponding source classes and require a substantive payload.
    if agent == "hackathon" and re.match(r"^(track|bounty)\b", low) and any(v in low for v in ("build ", "create ", "develop ", "implement ")):
        return True, "challenge_statement"
    if agent == "failure" and any(k in low for k in ("incident", "failure mode", "outage", "depeg", "cascade")) and any(v in low for v in ("triggered", "caused", "resulted", "led to")):
        return True, "incident"
    if agent == "data_availability" and any(k in low for k in ("dataset", "benchmark", "simulator", "benchmark suite")) and any(k in low for k in ("latency", "reproducible", "evaluation", "experiment", "metric")):
        return True, "benchmark_need"

    return False, ""

def _funding_eligibility_text(content: str) -> str:
    """Extract explicitly labelled eligibility sections/fields for problem-signal exclusion."""
    text = str(content or "")
    patterns = (
        r"(?ims)^\s*(?:#{1,6}\s*)?eligibility(?:\s+conditions?)?\s*[:\-]\s*(.*?)(?=^\s*(?:#{1,6}\s*)?(?:description|scope|expected outcomes?|trl|technology readiness level|deadline|opening date|funding amount|evaluation criteria|call identifier|status)\s*[:\-]|\Z)",
        r"(?ims)^\s*#{1,6}\s*eligibility(?:\s+&\s+conditions?)?\s*$\s*(.*?)(?=^\s*#{1,6}\s+|\Z)",
    )
    sections = []
    for pattern in patterns:
        sections.extend(match.group(1) for match in re.finditer(pattern, text))
    return "\n".join(sections)


def _is_funding_eligibility_fragment(candidate: str, eligibility_text: str, full_content: str) -> bool:
    """Do not promote a risk phrase that occurs only inside an eligibility rule."""
    candidate_text = re.sub(r"\s+", " ", str(candidate or "")).strip().casefold()
    eligibility = re.sub(r"\s+", " ", str(eligibility_text or "")).strip().casefold()
    full = re.sub(r"\s+", " ", str(full_content or "")).strip().casefold()
    if not candidate_text or candidate_text not in eligibility:
        return False
    # If the same source wording is also present outside the eligibility section,
    # preserve it as a potentially genuine technical problem signal.
    return full.count(candidate_text) <= eligibility.count(candidate_text)


def extract_problem_intelligence(content: str, title: str, evidence_bundle: dict, *, allow_llm_refinement: bool = True, research_area: Optional[str] = None, agent_name: Optional[str] = None) -> dict:
    evidence_content = (
        content
        if (agent_name or "").strip().lower() == "funding"
        else strip_collection_metadata(content)
    )
    paragraphs = _paragraphs(evidence_content)
    if (agent_name or "").strip().lower() == "funding":
        heading_only = re.compile(
            r"(?im)^\s{0,3}#{1,6}\s+(?:scope|expected outcomes?|description|background|rationale|overview|"
            r"problem preview|research mission|focus area|source details|funding details|requirements|"
            r"deadlines|timeline|call documents|programme theme)\s*$"
        )
        cleaned_content = _strip_expected_outcome_section(heading_only.sub("", evidence_content or ""))
        paragraphs = []
        for raw_paragraph in _paragraphs(cleaned_content):
            paragraphs.extend(_funding_candidate_segments(raw_paragraph))

    candidates = []
    funding_eligibility_text = (
        _funding_eligibility_text(content)
        if (agent_name or "").strip().lower() == "funding" else ""
    )

    for para in paragraphs:
        if (agent_name or "").strip().lower() == "funding":
            para = _clean_funding_candidate_text(para)
            if _is_funding_eligibility_fragment(para, funding_eligibility_text, evidence_content):
                continue
            if _is_funding_non_problem_sentence(para):
                continue
            # The call's own title restates the topic; it is not a problem statement.
            if title and re.sub(r"\W+", " ", para).strip().casefold() == re.sub(r"\W+", " ", str(title)).strip().casefold():
                continue
        if _is_boilerplate(para):
            continue
        if (
            (agent_name or "").strip().lower() == "funding"
            and _is_administrative_or_financial_rule(para)
        ):
            continue
        scores = _score_candidate(para, research_area)
        if scores["boilerplate_score"] >= 0.6:
            continue

        limitation = (
            _is_funding_limitation(para)
            if (agent_name or "").strip().lower() == "funding"
            else _is_genuine_limitation(para)
        )
        structured, structured_type = _is_structured_problem_signal(
            para, title=title, research_area=research_area, agent_name=agent_name
        )
        # Objectives and required work can contain words such as "risk" or "gap"
        # without identifying an existing problem. Only explicit problem/challenge
        # framing is allowed to override this conservative exclusion.
        if (
            (agent_name or "").strip().lower() == "funding"
            and _is_objective_or_task_statement(para)
            and not structured
        ):
            continue
        # An imperative instruction is not a problem unless it is explicitly framed.
        if (agent_name or "").strip().lower() == "funding" and re.match(
            r"^(?:build|create|develop|implement|block|limit|track|submit|apply|provide|support)\b",
            para, flags=re.IGNORECASE,
        ) and not structured:
            limitation = False
        if limitation or structured:
            problem_type = "identified_limitation" if limitation else structured_type
            candidates.append({
                "problem": para.strip(),
                "problem_type": problem_type,
                "evidence": [para],
                "evidence_refs": [],
                "specificity_score": scores["specificity_score"],
                "researchability_score": scores["researchability_score"],
                "boilerplate_score": scores["boilerplate_score"],
                "area_signal_score": scores["area_signal_score"],
                "area_signal_count": scores["area_signal_count"],
                "confidence": (
                    "High" if structured and scores["specificity_score"] >= 0.4
                    else "Medium" if structured or scores["researchability_score"] >= 0.4 or (
                        (agent_name or "").strip().lower() == "funding"
                        and limitation and scores["specificity_score"] >= 0.4
                    )
                    else "Low"
                )
            })
            
    if normalize_area(research_area) in AREA_KEYWORDS:
        candidates.sort(key=lambda c: (c["area_signal_score"], c["researchability_score"], c["specificity_score"], -c["boilerplate_score"]), reverse=True)
    else:
        candidates.sort(key=lambda c: (c["researchability_score"], c["specificity_score"], -c["boilerplate_score"]), reverse=True)
    candidates = candidates[:5]
    
    intelligence_mode = "deterministic"
    
    selected_problem = None
    problem_type = None
    problem_evidence = []
    problem_confidence = "Low"
    
    if candidates:
        best = candidates[0]
        selected_problem = best["problem"]
        problem_type = best["problem_type"]
        problem_evidence = best["evidence"]
        problem_confidence = best["confidence"]
        
    original_candidate = selected_problem
    if allow_llm_refinement and generate and test_connection and selected_problem:
        try:
            refined = _refine_with_llm(selected_problem, problem_evidence)
            if refined:
                selected_problem = refined
                intelligence_mode = "llm_assisted"
        except Exception:
            pass

    if not original_candidate:
        selected_problem = None
        problem_type = "unresolved"
        problem_confidence = "None"
        problem_evidence = []
        
    if selected_problem is not None:
        assert len(problem_evidence) >= 1, "Invariant failed: selected_problem must have >= 1 evidence"
        if intelligence_mode == "deterministic":
            found_in_content = any(selected_problem in ev for ev in problem_evidence) or selected_problem in evidence_content
            assert found_in_content, "Invariant failed: selected_problem must correspond to actual source text"

    return {
        "problem_candidates": candidates,
        "selected_problem": selected_problem,
        "original_candidate": original_candidate,
        "problem_type": problem_type,
        "problem_evidence": problem_evidence,
        "problem_confidence": problem_confidence,
        "intelligence_mode": intelligence_mode
    }
